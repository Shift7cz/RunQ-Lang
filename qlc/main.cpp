#include <fstream>
#include <sstream>

void setPath(const std::string& path) {
    std::filesystem::path absolutePath = std::filesystem::absolute(path);
    std::filesystem::path projectDir = absolutePath.parent_path();
    std::filesystem::current_path(projectDir);
    system("pwd");
}

std::string readFile(const std::string& path) {
    std::ifstream file(path);
    std::stringstream buffer;
    buffer << file.rdbuf();
    return buffer.str();
}

void compile(std::string path, std::string projectFile) {
    // ### FLAGS (will be set by config) ### //
    bool dontCompile = false; // if output.o, output.s and output will be generated by codegen
    bool devMode = false; // the debug printing of tokenization, ast, and llvm ir
    bool isLibrary = false; // will only generate .o and not final output
    bool emitAsm = false; // if .s file will be generated
    // ##################################### //

    //std::cout << "Project Path"; // for some reson its printing after
    setPath(path);

    Project prj;
    prj.load(projectFile);

    for (int i = 0; i < prj.flagList.size(); i++) {
        switch (prj.flagList[i]) {
            case DontCompile: dontCompile = true; break;
            case DevMode: devMode = true; std::cout << "DevMode is ment for compiler development mainly" << std::endl; break;
            case IsLibrary: isLibrary = true; break;
            case EmitAsm: emitAsm = true; break;
        }
    }

    for ( int i = 0; i < prj.libList.size(); i++) { // builds libraries
        std::cout << "Compiling dependent library: " << std::endl;

        std::filesystem::path originalPath = std::filesystem::current_path();

        compile(prj.libList[i], std::filesystem::path(prj.libList[i]).filename().string());

        std::filesystem::current_path(originalPath);
    }

    std::vector<Ast> asts;

    for (int i = 0; i < prj.runqList.size(); i++) {
        std::string source = readFile(prj.runqList[i]);

        if (devMode) std::cout << "Source ->\n" << source << "\n\nLexer out ->"<< std::endl;

        Lexer lexer(source, prj.runqList[i]);

        if (devMode) {
            bool isAtEnd = false;
            while (!isAtEnd) {
                Token token = lexer.nextToken();
                std::cout << token << std::endl;
                if (token.type == TokenType::EndOfFile) {
                    isAtEnd = true;
                }
            }
        }

        if (devMode) std::cout << "\n\nParser out ->" << std::endl;

        Lexer lexer2(source, prj.runqList[i]);
        Parser parser(lexer2);

        parser.parse();
        if (devMode) parser.ast.print();
        asts.push_back(std::move(parser.ast));
    }

    std::cout << "Merging asts..." << std::endl;
    for (int i = 1; i < asts.size(); i++) {
        asts[0].add(asts[i]);
    }

    if (devMode) asts[0].print();

    if (devMode) std::cout << "\n\nLLVM out -> \n" << std::endl;

    CodeGen codegen;
    codegen.cList = prj.cList;
    codegen.libList = prj.libList;
    codegen.compile(asts[0], !dontCompile, devMode, isLibrary, emitAsm);
}

int main() {
    std::cout << "Hello, RunQ!" << std::endl;

    std::string path = "../example/RunQ-Project.qlc";
    compile(path, std::filesystem::path(path).filename().string());  // todo: changeable
    return 0;
}